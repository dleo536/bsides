export const getCountryByCode = (countryCode) => {
  const normalizedCountryCode =
    typeof countryCode === "string" ? countryCode.trim().toUpperCase() : "";

  if (!normalizedCountryCode) {
    return null;
  }

  return (
    COUNTRY_OPTIONS.find((country) => country.code === normalizedCountryCode) ||
    null
  );
};

export const getMajorCitiesForCountry = (countryCode) => {
  const normalizedCountryCode =
    typeof countryCode === "string" ? countryCode.trim().toUpperCase() : "";

  if (!normalizedCountryCode) {
    return [];
  }

  return MAJOR_CITIES_BY_COUNTRY_CODE[normalizedCountryCode] || [];
};
